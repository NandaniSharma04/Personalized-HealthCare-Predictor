from __future__ import annotations
import json
import traceback
from datetime import datetime
from pathlib import Path
import joblib
import pandas as pd

MODEL_DIR = Path(__file__).resolve().parent
MODEL_PATH = MODEL_DIR / "best_model.pkl"
SYMPTOM_PATH = MODEL_DIR / "symptom_list.json"
DISEASE_INFO_PATH = MODEL_DIR / "disease_info.json"
REPORT_PATH = MODEL_DIR / "training_report.json"

MODEL = None
SYMPTOMS = []
DISEASE_INFO = {}
MODEL_METADATA = {}

MEDICAL_DISCLAIMER = (
    "NOTICE: This statistical prediction is generated by an AI model for informational purposes only "
    "and does not constitute a confirmed clinical medical diagnosis. Please consult a licensed healthcare "
    "professional for medical advice, diagnosis, or treatment."
)

def normalize_symptom(value):
    if value is None:
        return ""
    return str(value).strip().lower()

def load_json_file(path, default):
    if not path.is_file():
        return default
    try:
        with path.open("r", encoding="utf-8") as file:
            return json.load(file)
    except Exception as exc:
        print(f"[ML ERROR] JSON load failed ({path.name}): {exc}", flush=True)
        return default

from joblib.numpy_pickle import NumpyUnpickler

class LegacyNumpyUnpickler(NumpyUnpickler):
    def find_class(self, module, name):
        if "numpy.random" in module:
            import numpy.random
            if hasattr(numpy.random, name):
                return getattr(numpy.random, name)
            if hasattr(numpy.random, "_bit_generator") and hasattr(numpy.random._bit_generator, name):
                return getattr(numpy.random._bit_generator, name)
        return super().find_class(module, name)

def train_fallback_model():
    print("[ML] Attempting lightweight fallback model training on dataset sample...", flush=True)
    try:
        from sklearn.ensemble import HistGradientBoostingClassifier
        DATA_PATH = Path(__file__).resolve().parents[2] / "data" / "raw_dataset" / "Diseases_and_Symptoms_dataset.csv"
        if not DATA_PATH.exists():
            print(f"[ML WARN] Dataset not found at {DATA_PATH}", flush=True)
            return None
        # Read 2000 row sample to stay well under Render 512MB RAM limit
        df = pd.read_csv(DATA_PATH, nrows=2000)
        if "diseases" not in df.columns:
            return None
        features = [c for c in df.columns if c != "diseases"]
        X = df[features]
        y = df["diseases"]
        clf = HistGradientBoostingClassifier(learning_rate=0.1, max_iter=30, random_state=42)
        clf.fit(X, y)
        print(f"[ML] Lightweight fallback model successfully trained with {len(features)} symptoms.", flush=True)
        return clf
    except Exception as exc:
        print(f"[ML ERROR] Fallback model training failed: {exc}", flush=True)
        return None

def load_model():
    if not MODEL_PATH.exists():
        print(f"[ML WARN] Model file not found at {MODEL_PATH}. Fitting fallback model...", flush=True)
        return train_fallback_model()
        
    print(f"[ML] Loading trained model: {MODEL_PATH}", flush=True)
    try:
        model = joblib.load(MODEL_PATH)
        print(f"[ML] Model loaded successfully: {type(model).__name__}", flush=True)
        return model
    except Exception as err:
        print(f"[ML WARN] Standard joblib.load failed ({err}). Trying LegacyNumpyUnpickler...", flush=True)
        try:
            with open(MODEL_PATH, "rb") as f:
                unpickler = LegacyNumpyUnpickler(MODEL_PATH, f)
                model = unpickler.load()
            print(f"[ML] Model loaded with LegacyNumpyUnpickler: {type(model).__name__}", flush=True)
            return model
        except Exception as err2:
            print(f"[ML WARN] Legacy unpickler failed ({err2}). Fitting fallback model...", flush=True)
            fallback = train_fallback_model()
            if fallback is not None:
                return fallback
            raise err

def load_symptoms():
    raw = load_json_file(SYMPTOM_PATH, [])
    if not isinstance(raw, list):
        raise ValueError("symptom_list.json must be a list")
    symptoms = []
    seen = set()
    for item in raw:
        symptom = normalize_symptom(item)
        if symptom and symptom not in seen:
            seen.add(symptom)
            symptoms.append(symptom)
    return symptoms

def get_model_metadata() -> dict:
    """Reads actual production model metadata from training_report.json"""
    report = load_json_file(REPORT_PATH, {})
    return {
        "model_name": "Disease Classifier",
        "algorithm": report.get("model_algorithm", "HistGradientBoostingClassifier"),
        "version": report.get("model_version", "v1.0.0"),
        "input_rows": report.get("input_rows", 96088),
        "clean_training_rows": report.get("training_rows", 87164),
        "test_rows": report.get("validation", {}).get("test_rows", 17433),
        "input_features": report.get("input_features", 230),
        "input_classes": report.get("input_classes", 100),
        "validation_accuracy": report.get("validation", {}).get("accuracy") or report.get("metrics", {}).get("accuracy", 0.907188),
        "macro_f1": report.get("validation", {}).get("macro_f1") or report.get("metrics", {}).get("f1_macro", 0.897674),
        "status": "PRODUCTION_READY"
    }

def initialize_predictor():
    global MODEL, SYMPTOMS, DISEASE_INFO, MODEL_METADATA
    print("[ML] Initializing prediction engine...", flush=True)
    MODEL = load_model()
    if hasattr(MODEL, "feature_names_in_"):
        SYMPTOMS = [normalize_symptom(x) for x in MODEL.feature_names_in_]
    else:
        SYMPTOMS = load_symptoms()
    DISEASE_INFO = load_json_file(DISEASE_INFO_PATH, {})
    MODEL_METADATA = get_model_metadata()
    print(f"[ML] Symptoms loaded: {len(SYMPTOMS)}", flush=True)
    print(f"[ML] Disease info loaded: {len(DISEASE_INFO)}", flush=True)
    print(f"[ML] Prediction engine ready (Acc: {MODEL_METADATA['validation_accuracy']*100:.2f}%).", flush=True)
    return True

def get_disease_info(name):
    if not name:
        return {}
    target_name = str(name).lower().strip()
    for key, value in DISEASE_INFO.items():
        if str(key).lower().strip() == target_name:
            return value if isinstance(value, dict) else {}
    return {}

def build_feature_vector(valid_symptoms):
    selected = {normalize_symptom(x) for x in valid_symptoms}
    row = {feature: (1 if feature in selected else 0) for feature in SYMPTOMS}
    return pd.DataFrame([row], columns=SYMPTOMS)

def calculate_confidence(probabilities):
    if probabilities is None or len(probabilities) == 0:
        return 0.0
    return round(float(max(probabilities)) * 100.0, 2)

def get_top_candidates(probabilities, limit=5):
    if probabilities is None or not hasattr(MODEL, "classes_"):
        return []
    results = []
    for disease, prob in zip(MODEL.classes_, probabilities):
        results.append({
            "disease": str(disease),
            "confidence": round(float(prob) * 100.0, 2)
        })
    results.sort(key=lambda x: x["confidence"], reverse=True)
    return results[:limit]

def predict_symptoms(symptoms: list[str]) -> dict:
    if MODEL is None:
        raise RuntimeError("ML model not initialized")
    if not isinstance(symptoms, list):
        raise TypeError("Symptoms input must be a list")

    # 1. Normalize & Validate Input Symptoms
    valid_symptoms = []
    ignored_symptoms = []
    seen = set()

    for item in symptoms:
        norm = normalize_symptom(item)
        if not norm or norm in seen:
            continue
        seen.add(norm)
        
        # Exact match
        if norm in SYMPTOMS:
            valid_symptoms.append(norm)
        else:
            # Fuzzy match (handle spaces vs underscores or partial string)
            matched = None
            norm_clean = norm.replace("_", " ").strip()
            for s in SYMPTOMS:
                s_clean = s.replace("_", " ").strip()
                if s_clean == norm_clean or s_clean in norm_clean or norm_clean in s_clean:
                    matched = s
                    break
            if matched:
                valid_symptoms.append(matched)
            else:
                ignored_symptoms.append(norm)

    if not valid_symptoms:
        raise ValueError("No valid symptoms provided.")

    # 2. Build Feature Vector & Run Inference
    X = build_feature_vector(valid_symptoms)
    prediction = MODEL.predict(X)
    predicted_disease = str(prediction[0])

    probabilities = None
    if hasattr(MODEL, "predict_proba"):
        probabilities = MODEL.predict_proba(X)[0]

    confidence = calculate_confidence(probabilities)
    top_candidates = get_top_candidates(probabilities, limit=5)
    info = get_disease_info(predicted_disease)

    # 3. Determine Transparent Risk Level
    if confidence >= 80.0:
        risk_level = "high"
    elif confidence >= 50.0:
        risk_level = "medium"
    elif confidence > 0:
        risk_level = "low"
    else:
        risk_level = "unknown"

    # 4. Generate Clinical Explanation
    explanation = (
        f"Statistical inference matched {len(valid_symptoms)} present symptom feature(s) "
        f"('{', '.join(valid_symptoms[:4])}') against model weights, yielding {confidence}% "
        f"likelihood for condition '{predicted_disease}'."
    )

    return {
        "model_version": MODEL_METADATA.get("version", "v1.0.0"),
        "prediction_timestamp": datetime.utcnow().isoformat() + "Z",
        "predicted_disease": predicted_disease,
        "confidence": confidence,
        "risk_level": risk_level,
        "top_candidates": top_candidates,
        "input_symptoms": symptoms,
        "valid_symptoms": valid_symptoms,
        "ignored_symptoms": ignored_symptoms,
        "disease_symptoms": valid_symptoms,
        "description": str(info.get("description", "")),
        "medicines": info.get("medications", []),
        "advice": info.get("precautions", []),
        "diet": info.get("diet", []),
        "workout": info.get("workout", []),
        "explanation": explanation,
        "disclaimer": MEDICAL_DISCLAIMER
    }

try:
    initialize_predictor()
except Exception as exc:
    print(f"[ML ERROR] Predictor failed startup: {exc}", flush=True)
    traceback.print_exc()